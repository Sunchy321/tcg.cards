import { magicFormatKeywordMap } from './data/format-keywords';

/** Expand a format keyword to its target formats; literal format ids pass through unchanged. */
export function resolveFormats(format: string | null): string[] {
  if (format == null) {
    return [];
  }
  return magicFormatKeywordMap[format] ?? [format];
}

/** The authored announcement-item fields the projection derives from. */
export interface ProjectionItemInput {
  type:          string;
  format:        string | null;
  status:        string | null;
  effectiveDate: string | null;
  cardId:        string | null;
  setId:         string | null;
  relatedCards:  string[];
}

/** Lookup data the caller resolves from the database: set→cards fan-out, sentinel group card lists, and each card's earliest print release date. */
export interface ProjectionContext {
  setCards:                  Record<string, string[]>;
  groupCards:                Record<string, string[]>;
  cardReleaseDates:          Record<string, string>;
  announcementEffectiveDate: string;
}

/** A per-card entry generated by sentinel group expansion: the card, its status, and its own effective date. */
export interface ProjectedEntry {
  cardId:        string;
  status:        string | null;
  effectiveDate: string;
}

/** The derived projection of one announcement item; entries exist only for sentinel group items. */
export interface ItemProjection {
  formats: string[];
  cards:   string[];
  entries: ProjectedEntry[];
}

/** A cardId starting with # addresses a sentinel group (e.g. #conspiracy) rather than a single card. */
export function isSentinelCardId(cardId: string): boolean {
  return cardId.startsWith('#');
}

/** The date an item takes hold: the item's own effective date, else the announcement's. */
export function resolveEffectiveDate(item: { effectiveDate: string | null }, context: ProjectionContext): string {
  return item.effectiveDate ?? context.announcementEffectiveDate;
}

/**
 * Derive one item's projection: keyword-expanded formats, the affected card
 * set (direct cardId + relatedCards, set fan-out for set_change, group
 * expansion for sentinel cardIds), and for sentinel items the per-card
 * entries. A sentinel card already released at the item's effective date is
 * banned at that date; a card released later is banned at its release date.
 */
export function projectItem(item: ProjectionItemInput, context: ProjectionContext): ItemProjection {
  const formats = resolveFormats(item.format);
  const cards = new Set<string>();
  const entries: ProjectedEntry[] = [];
  const effectiveDate = resolveEffectiveDate(item, context);

  if (item.cardId != null && !isSentinelCardId(item.cardId)) {
    cards.add(item.cardId);
  }
  for (const id of item.relatedCards) {
    cards.add(id);
  }
  if (item.type === 'set_change' && item.setId != null) {
    for (const id of context.setCards[item.setId] ?? []) {
      cards.add(id);
    }
  }
  if (item.cardId != null && isSentinelCardId(item.cardId)) {
    const groupCards = context.groupCards[item.cardId.slice(1)] ?? [];
    for (const cardId of groupCards) {
      cards.add(cardId);
      const releaseDate = context.cardReleaseDates[cardId];
      entries.push({
        cardId,
        status:        item.status,
        effectiveDate: releaseDate != null && releaseDate > effectiveDate ? releaseDate : effectiveDate,
      });
    }
  }

  return { formats, cards: [...cards], entries };
}
